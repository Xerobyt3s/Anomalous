typedef struct SlotEntry {
    u32 cp;
    u32 slot;
    b32 wide;
    b32 used;
} SlotEntry;

static u32 s_atlas;
static u32 s_next_slot;
static SlotEntry s_hash[TERM_FONT_HASH_SIZE];
static u32 s_missing_slot;

#define ATLAS_PX_W (TERM_FONT_ATLAS_COLS * TERM_FONT_SLOT_W)
#define ATLAS_PX_H (TERM_FONT_ATLAS_ROWS * TERM_FONT_SLOT_H)

b32 term_font_cp_wide(u32 cp)
{
    return (cp >= 0x1100 && cp <= 0x115F)
        || (cp >= 0x2E80 && cp <= 0xA4CF)
        || (cp >= 0xAC00 && cp <= 0xD7A3)
        || (cp >= 0xF900 && cp <= 0xFAFF)
        || (cp >= 0xFF00 && cp <= 0xFF60)
        || (cp >= 0xFFE0 && cp <= 0xFFE6);
}

static void slot_upload(u32 slot, const u8* pixels)
{
    i32 x = (i32)(slot % TERM_FONT_ATLAS_COLS) * TERM_FONT_SLOT_W;
    i32 y = (i32)(slot / TERM_FONT_ATLAS_COLS) * TERM_FONT_SLOT_H;
    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    glTextureSubImage2D(s_atlas, 0, x, y, TERM_FONT_SLOT_W, TERM_FONT_SLOT_H,
                        GL_RED, GL_UNSIGNED_BYTE, pixels);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 4);
}

static void bake_builtin(void)
{
    u8 pixels[TERM_FONT_SLOT_W * TERM_FONT_SLOT_H];
    for (i32 i = 0; i < TERM_FONT_BUILTIN_COUNT; i++) {
        memset(pixels, 0, sizeof(pixels));
        for (i32 row = 0; row < TERM_FONT_BUILTIN_CELL; row++) {
            const char* bits = FONT_GLYPHS[i].rows[row];
            for (i32 col = 0; col < TERM_FONT_BUILTIN_CELL; col++) {
                if (bits[col] == '#') {
                    pixels[(row + 2) * TERM_FONT_SLOT_W + col] = 255;
                }
            }
        }
        u32 slot = (u32)((u8)FONT_GLYPHS[i].code - 32);
        slot_upload(slot, pixels);
    }
}

static void bake_missing_box(u32 slot)
{
    u8 pixels[TERM_FONT_SLOT_W * TERM_FONT_SLOT_H];
    memset(pixels, 0, sizeof(pixels));
    for (i32 x = 1; x < 7; x++) {
        pixels[3 * TERM_FONT_SLOT_W + x] = 255;
        pixels[9 * TERM_FONT_SLOT_W + x] = 255;
    }
    for (i32 y = 3; y <= 9; y++) {
        pixels[y * TERM_FONT_SLOT_W + 1] = 255;
        pixels[y * TERM_FONT_SLOT_W + 6] = 255;
    }
    slot_upload(slot, pixels);
}

b32 term_font_init(void)
{
    memset(s_hash, 0, sizeof(s_hash));
    glCreateTextures(GL_TEXTURE_2D, 1, &s_atlas);
    glTextureStorage2D(s_atlas, 1, GL_R8, ATLAS_PX_W, ATLAS_PX_H);
    glTextureParameteri(s_atlas, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTextureParameteri(s_atlas, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTextureParameteri(s_atlas, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTextureParameteri(s_atlas, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    u8 clear_px[TERM_FONT_SLOT_W * TERM_FONT_SLOT_H];
    memset(clear_px, 0, sizeof(clear_px));
    for (u32 i = 0; i < TERM_FONT_MAX_SLOTS; i++) {
        slot_upload(i, clear_px);
    }
    bake_builtin();
    s_next_slot = TERM_FONT_BUILTIN_COUNT;
    s_missing_slot = s_next_slot++;
    bake_missing_box(s_missing_slot);
    return 1;
}

void term_font_shutdown(void)
{
    glDeleteTextures(1, &s_atlas);
    s_atlas = 0;
}

u32 term_font_texture(void)
{
    return s_atlas;
}

static u32 bake_codepoint(u32 cp, b32 wide)
{
    i32 glyph = 0;
    i32 face_idx = fontchain_find(cp, &glyph);
    const stbtt_fontinfo* face = fontchain_face(face_idx);
    if (!face || !glyph) {
        return s_missing_slot;
    }
    if (s_next_slot >= TERM_FONT_MAX_SLOTS) {
        log_warn("term_font: atlas full at cp %u", cp);
        return s_missing_slot;
    }

    i32 box_w = wide ? 16 : 8;
    f32 pixel_h = wide ? 11.0f : 10.0f;
    f32 scale = stbtt_ScaleForPixelHeight(face, pixel_h);
    i32 baseline = 10;

    i32 x0, y0, x1, y1;
    stbtt_GetGlyphBitmapBox(face, glyph, scale, scale, &x0, &y0, &x1, &y1);
    i32 gw = x1 - x0;
    i32 gh = y1 - y0;
    if (gw <= 0 || gh <= 0) {
        return s_missing_slot;
    }
    if (gw > 32) { gw = 32; }
    if (gh > 24) { gh = 24; }

    ArenaTemp temp = arena_temp_begin(&g_frame_arena);
    u8* raster = arena_push_array(&g_frame_arena, u8, (u64)gw * gh);
    stbtt_MakeGlyphBitmap(face, raster, gw, gh, gw, scale, scale, glyph);

    u8 pixels[TERM_FONT_SLOT_W * TERM_FONT_SLOT_H];
    memset(pixels, 0, sizeof(pixels));
    i32 dst_x0 = (box_w - gw) / 2;
    i32 dst_y0 = baseline + y0;
    for (i32 y = 0; y < gh; y++) {
        i32 dy = dst_y0 + y;
        if (dy < 0 || dy >= TERM_FONT_SLOT_H) {
            continue;
        }
        for (i32 x = 0; x < gw; x++) {
            i32 dx = dst_x0 + x;
            if (dx < 0 || dx >= box_w) {
                continue;
            }
            if (raster[y * gw + x] >= 96) {
                pixels[dy * TERM_FONT_SLOT_W + dx] = 255;
            }
        }
    }
    arena_temp_end(temp);

    u32 slot = s_next_slot++;
    slot_upload(slot, pixels);
    return slot;
}

u32 term_font_slot(u32 cp, b32* out_wide)
{
    if (cp >= 32 && cp <= 127) {
        if (out_wide) {
            *out_wide = 0;
        }
        return cp - 32;
    }
    b32 wide = term_font_cp_wide(cp);
    if (out_wide) {
        *out_wide = wide;
    }
    u32 h = (cp * 2654435761u) & (TERM_FONT_HASH_SIZE - 1);
    for (u32 probe = 0; probe < TERM_FONT_HASH_SIZE; probe++) {
        SlotEntry* e = &s_hash[(h + probe) & (TERM_FONT_HASH_SIZE - 1)];
        if (e->used && e->cp == cp) {
            return e->slot;
        }
        if (!e->used) {
            e->used = 1;
            e->cp = cp;
            e->wide = wide;
            e->slot = bake_codepoint(cp, wide);
            return e->slot;
        }
    }
    return s_missing_slot;
}
